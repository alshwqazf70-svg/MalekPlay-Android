package com.malekplay.translation

import java.nio.charset.Charset
import java.nio.charset.CharacterCodingException
import java.nio.charset.StandardCharsets
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class SrtSubtitleParserTest {

    @Test
    fun decodesUtf8BomAndUtf16LittleAndBigEndianFiles() {
        val text = "1\n00:00:01,000 --> 00:00:02,000\nHello"
        val utf8 = byteArrayOf(0xEF.toByte(), 0xBB.toByte(), 0xBF.toByte()) +
            text.toByteArray(StandardCharsets.UTF_8)
        val utf16Le = byteArrayOf(0xFF.toByte(), 0xFE.toByte()) +
            text.toByteArray(StandardCharsets.UTF_16LE)
        val utf16Be = byteArrayOf(0xFE.toByte(), 0xFF.toByte()) +
            text.toByteArray(StandardCharsets.UTF_16BE)

        assertEquals(text, SrtSubtitleParser.decode(utf8))
        assertEquals(text, SrtSubtitleParser.decode(utf16Le))
        assertEquals(text, SrtSubtitleParser.decode(utf16Be))
    }

    @Test
    fun decodesArabicWindows1256WithoutBom() {
        val arabic = "مرحبا بالعالم"
        val bytes = arabic.toByteArray(Charset.forName("windows-1256"))
        assertEquals(arabic, SrtSubtitleParser.decode(bytes))
    }

    @Test
    fun rejectsTruncatedUtf16AndMalformedUtf8BomPayloads() {
        val truncatedUtf16 = byteArrayOf(0xFF.toByte(), 0xFE.toByte(), 0x41)
        val malformedUtf8 = byteArrayOf(
            0xEF.toByte(), 0xBB.toByte(), 0xBF.toByte(), 0xC3.toByte(), 0x28
        )

        assertThrows(IllegalArgumentException::class.java) {
            SrtSubtitleParser.decode(truncatedUtf16)
        }
        assertThrows(CharacterCodingException::class.java) {
            SrtSubtitleParser.decode(malformedUtf8)
        }
    }

    @Test
    fun acceptsLongHoursAndWebVttStyleCueSettingsButRejectsMalformedEndTimestamp() {
        assertEquals(1, SrtSubtitleParser.timingLineIndex(listOf(
            "1", "123:00:01,250 --> 123:00:03,500", "Text"
        )))
        assertEquals(1, SrtSubtitleParser.timingLineIndex(listOf(
            "1", "00:00:01.250 --> 00:00:03.500 X1:10 X2:90", "Text"
        )))
        assertEquals(-1, SrtSubtitleParser.timingLineIndex(listOf(
            "1", "00:00:01,250 --> not-a-time", "Text"
        )))
    }

    @Test
    fun preservesCueTimingAndFormattingMarkup() {
        val source = "1\n00:00:01,000 --> 00:00:02,000\n<i>Hello</i>\n\n2\n00:00:03,000 --> 00:00:04,000\nWorld"
        val cues = SrtSubtitleParser.splitBlocks(source)
        assertEquals(2, cues.size)

        val lines = cues.first().split('\n')
        assertEquals(1, SrtSubtitleParser.timingLineIndex(lines))
        val (masked, tags) = SrtSubtitleParser.maskMarkup("<i>Hello</i>")
        assertTrue(masked.contains("§T0§"))
        assertEquals("<i>Bonjour</i>", SrtSubtitleParser.restoreMarkup(
            masked.replace("Hello", "Bonjour"), tags
        ))
    }

    @Test
    fun supportsCommaAndDotTimestampSeparators() {
        assertEquals(1, SrtSubtitleParser.timingLineIndex(listOf(
            "7", "00:00:01.250 --> 00:00:03.500", "Text"
        )))
    }
    @Test
    fun convertsWebVttHeaderMetadataAndShortTimestampsIntoValidSrtCues() {
        val vtt = """WEBVTT
Kind: captions
Language: en

NOTE generated by test
This note must not become a subtitle cue

STYLE
::cue { color: white }

intro
00:01.250 --> 00:03.500 align:start
Hello there

00:00:04.000 --> 00:00:05.250
Second cue
"""
        val cues = SrtSubtitleParser.splitBlocks(vtt)
        assertEquals(2, cues.size)
        assertEquals("00:01,250 --> 00:03,500 align:start", cues[0].lines()[1])
        assertEquals("00:00:04,000 --> 00:00:05,250", cues[1].lines()[0])
        assertEquals(-1, SrtSubtitleParser.timingLineIndex(listOf("WEBVTT")))
        assertEquals(1, SrtSubtitleParser.timingLineIndex(cues[0].lines()))
    }

    @Test
    fun preservesSrtCommaTimestampsAndCueIdentifiers() {
        val srt = "1\n00:00:01,000 --> 00:00:02,000\n<i>Hello</i>"
        val cues = SrtSubtitleParser.splitBlocks(srt)
        assertEquals(1, cues.size)
        assertEquals(srt, cues.single())
    }

    @Test
    fun doesNotTreatSrtCueTextAsWebVttMetadata() {
        val srt = "1\n00:00:01,000 --> 00:00:02,000\nNOTE this is spoken dialogue"
        assertEquals(1, SrtSubtitleParser.splitBlocks(srt).size)
    }


    @Test
    fun detectsUtf16LittleAndBigEndianWithoutBom() {
        val text = "1\\n00:00:01,000 --> 00:00:02,000\\nHello subtitle"
        val utf16Le = text.toByteArray(StandardCharsets.UTF_16LE)
        val utf16Be = text.toByteArray(StandardCharsets.UTF_16BE)

        assertEquals(text, SrtSubtitleParser.decode(utf16Le))
        assertEquals(text, SrtSubtitleParser.decode(utf16Be))
    }


    @Test
    fun parsesAssAndSsaDialogueWithCommaTextAndFormattingOverrides() {
        val ass = """[Script Info]
Title: ASS parser test

[V4+ Styles]
Format: Name, Fontname, Fontsize

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:01.25,0:00:03.50,Default,,0,0,0,,{\i1}Hello, world\Nsecond line
Dialogue: 0,0:00:04.00,0:00:05.25,Default,,0,0,0,,Another cue
"""
        val cues = SrtSubtitleParser.splitBlocks(ass, "ass")
        assertEquals(2, cues.size)
        assertEquals("00:00:01,250 --> 00:00:03,500", cues[0].lines()[1])
        assertEquals("Hello, world\nsecond line", cues[0].lines().drop(2).joinToString("\n"))
        assertEquals("00:00:04,000 --> 00:00:05,250", cues[1].lines()[1])
        assertEquals(1, SrtSubtitleParser.timingLineIndex(cues[0].lines()))
    }


    @Test
    fun detectsSubtitleFormatFromContentBeforeFilenameHints() {
        assertEquals(
            "vtt",
            SrtSubtitleParser.detectFormat("00:01.250 --> 00:02.500\\nHello")
        )
        assertEquals(
            "srt",
            SrtSubtitleParser.detectFormat("1\\n00:00:01,000 --> 00:00:02,000\\nHello")
        )
        assertEquals(
            "ass",
            SrtSubtitleParser.detectFormat("[Script Info]\\n[Events]\\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hello")
        )
    }

}
